package local.station.agent;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Arrays;

/** Generates actual production bytes for independent Python/Pillow decoding. */
public final class ScheduleGifHostTest {
    private static int assertions;
    private static void check(boolean condition) {
        assertions++;
        if (!condition) throw new AssertionError("GIF host boundary failure");
    }
    public static void main(String[] args) throws Exception {
        Path output = Paths.get(args[0]);
        int[] invalid = {Integer.MIN_VALUE, -1, 0, 86401, Integer.MAX_VALUE};
        for (int seconds : invalid) {
            boolean rejected = false;
            try { ScheduleGif.countdown(seconds); }
            catch (IllegalArgumentException expected) { rejected = true; }
            check(rejected);
        }
        int[] valid = {1, 2, 5, 9, 10, 11, 59, 60, 61, 599, 600, 3599, 3600, 3601, 35999, 36000, 86399, 86400};
        for (int seconds : valid) {
            byte[] gif = ScheduleGif.countdown(seconds);
            check(gif.length > 200 && gif.length < 4096);
            check(Arrays.equals(gif, ScheduleGif.countdown(seconds)));
            Files.write(output.resolve(seconds + ".gif"), gif);
        }
        System.out.println(assertions + " GIF host assertions passed; generated bytes only");
    }
}
